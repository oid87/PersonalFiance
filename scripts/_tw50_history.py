def _timeline():
    """[(生效日, 該日起的成分股)]，由現行名單倒推；最早一筆生效日為空字串。"""
    s, out = set(CURRENT), []
    for _, eff, add, drop in sorted(CHANGES, key=lambda r: r[1], reverse=True):
        out.append((eff, frozenset(s)))
        s = (s - set(add)) | set(drop)
    out.append(("", frozenset(s)))
    return sorted(out)


TIMELINE = _timeline()
_EFFECTIVE = [e for e, _ in TIMELINE]


def members_on(d_iso: str) -> frozenset:
    """d_iso（YYYY-MM-DD）當天的臺灣50成分股代號。"""
    return TIMELINE[bisect.bisect_right(_EFFECTIVE, d_iso) - 1][1]
